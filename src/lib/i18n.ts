export const dictionaries: Record<Locale, Dictionary> = { "pt-BR": ptBR, "en-US": enUS, es, fr };

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && locales.includes(value as Locale);
}

export function translate(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}) {
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), dictionaries[locale][key]);
}